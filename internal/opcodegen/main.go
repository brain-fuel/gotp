// Command opcodegen turns Erlang/OTP's pinned genop.tab into a Go lookup table.
package main

import (
	"bufio"
	"bytes"
	"crypto/sha256"
	"flag"
	"fmt"
	"go/format"
	"os"
	"regexp"
	"sort"
	"strconv"
)

type opcode struct {
	number int
	name   string
	arity  int
}

var (
	formatRE = regexp.MustCompile(`^BEAM_FORMAT_NUMBER=([0-9]+)$`)
	opcodeRE = regexp.MustCompile(`^([0-9]+):[[:space:]]+([a-z][a-zA-Z0-9_]*)/([0-9]+)(?:[[:space:]]|$)`)
)

func main() {
	input := flag.String("input", "", "path to OTP genop.tab")
	output := flag.String("output", "", "path to generated Go file")
	version := flag.String("version", "", "pinned OTP version")
	flag.Parse()

	if *input == "" || *output == "" || *version == "" {
		fail("input, output, and version are required")
	}

	source, err := os.ReadFile(*input)
	if err != nil {
		fail("read %s: %v", *input, err)
	}
	formatNumber, ops, err := parse(source)
	if err != nil {
		fail("parse %s: %v", *input, err)
	}
	digest := fmt.Sprintf("%x", sha256.Sum256(source))

	generated, err := render(*version, digest, formatNumber, ops)
	if err != nil {
		fail("render: %v", err)
	}
	if err := os.WriteFile(*output, generated, 0o644); err != nil {
		fail("write %s: %v", *output, err)
	}
}

func parse(source []byte) (int, []opcode, error) {
	formatNumber := -1
	seen := make(map[int]bool)
	var ops []opcode

	scanner := bufio.NewScanner(bytes.NewReader(source))
	for scanner.Scan() {
		line := scanner.Text()
		if match := formatRE.FindStringSubmatch(line); match != nil {
			value, err := strconv.Atoi(match[1])
			if err != nil {
				return 0, nil, fmt.Errorf("invalid format number: %w", err)
			}
			formatNumber = value
			continue
		}
		match := opcodeRE.FindStringSubmatch(line)
		if match == nil {
			continue
		}
		number, err := strconv.Atoi(match[1])
		if err != nil {
			return 0, nil, fmt.Errorf("invalid opcode number on %q: %w", line, err)
		}
		arity, err := strconv.Atoi(match[3])
		if err != nil {
			return 0, nil, fmt.Errorf("invalid opcode arity on %q: %w", line, err)
		}
		if number < 1 || number > 255 {
			return 0, nil, fmt.Errorf("opcode %d does not fit in one byte", number)
		}
		if seen[number] {
			return 0, nil, fmt.Errorf("duplicate opcode %d", number)
		}
		seen[number] = true
		ops = append(ops, opcode{number: number, name: match[2], arity: arity})
	}
	if err := scanner.Err(); err != nil {
		return 0, nil, err
	}
	if formatNumber < 0 {
		return 0, nil, fmt.Errorf("BEAM_FORMAT_NUMBER is missing")
	}
	if len(ops) == 0 {
		return 0, nil, fmt.Errorf("no opcodes found")
	}

	sort.Slice(ops, func(i, j int) bool { return ops[i].number < ops[j].number })
	return formatNumber, ops, nil
}

func render(version, digest string, formatNumber int, ops []opcode) ([]byte, error) {
	var out bytes.Buffer
	fmt.Fprintln(&out, "// Code generated by internal/opcodegen; DO NOT EDIT.")
	fmt.Fprintln(&out)
	fmt.Fprintln(&out, "package beam")
	fmt.Fprintln(&out)
	fmt.Fprintf(&out, "const OpcodeSourceVersion = %q\n", version)
	fmt.Fprintf(&out, "const OpcodeSourceSHA256 = %q\n", digest)
	fmt.Fprintf(&out, "const OpcodeFormatNumber uint32 = %d\n", formatNumber)
	fmt.Fprintf(&out, "const generatedMaxOpcode byte = %d\n", ops[len(ops)-1].number)
	fmt.Fprintln(&out)
	fmt.Fprintln(&out, "type generatedOpcodeSpec struct {")
	fmt.Fprintln(&out, "\tname string")
	fmt.Fprintln(&out, "\tarity uint8")
	fmt.Fprintln(&out, "}")
	fmt.Fprintln(&out)
	fmt.Fprintf(&out, "var generatedOpcodeTable = [%d]generatedOpcodeSpec{\n", ops[len(ops)-1].number+1)
	for _, op := range ops {
		fmt.Fprintf(&out, "\t%d: {name: %q, arity: %d},\n", op.number, op.name, op.arity)
	}
	fmt.Fprintln(&out, "}")

	return format.Source(out.Bytes())
}

func fail(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "opcodegen: "+format+"\n", args...)
	os.Exit(1)
}
